"""Generates ref/mp3/tables/{huffman,synth_window}.zig.

Huffman: runs minimp3's codebook walk (third_party/minimp3, CC0) on every codeword of every
Layer III table and writes the canonical (code, len) per symbol, symbol index x * width + y,
and v * 8 + w * 4 + x * 2 + y for the count1 tables.
Synthesis window: ISO/IEC 11172-3's D[i] from PDMP3's g_synth_dtbl (public domain).
"""
import re
import sys

root = sys.argv[1]
src = open(f"{root}/third_party/minimp3/minimp3.h").read()


def array(name, text):
    m = re.search(r"\b" + name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    return [int(v) for v in re.findall(r"-?\d+", m.group(1))]


tabs = array("tabs", src)
tabindex = array("tabindex", src)
tab32 = array("tab32", src)
tab33 = array("tab33", src)
linbits = array("g_linbits", src)

# ISO table dimensions (xlen = ylen) per table number; 0, 4 and 14 are not used.
WIDTH = {1: 2, 2: 3, 3: 3, 5: 4, 6: 4, 7: 6, 8: 6, 9: 6, 10: 8, 11: 8, 12: 8, 13: 16, 15: 16, 16: 16, 24: 16}
NB = 19  # longest codeword


def walk_pair(base, window):
    pos = 0

    def peek(n):
        return (window >> (32 - pos - n)) & ((1 << n) - 1)

    w = 5
    leaf = tabs[base + peek(5)]
    while leaf < 0:
        pos += w
        w = leaf & 7
        leaf = tabs[base + peek(w) - (leaf >> 3)]
    return pos + (leaf >> 8), leaf & 15, (leaf >> 4) & 15


def walk_quad(tab, window):
    leaf = tab[window >> 28]
    if not leaf & 8:
        leaf = tab[(leaf >> 3) + ((window << 4 & 0xFFFFFFFF) >> (32 - (leaf & 3)))]
    return leaf & 7, (leaf >> 4) & 15


def enumerate_codes(step):
    """step(window) -> (len, symbol); walks the code space codeword by codeword."""
    codes = {}
    p = 0
    while p < 1 << NB:
        length, sym = step(p << (32 - NB))
        assert 1 <= length <= NB
        assert sym not in codes, f"symbol {sym} twice"
        codes[sym] = (p >> (NB - length), length)
        p += 1 << (NB - length)
    return codes


def pair_step(t):
    base = tabindex[t]
    width = WIDTH[t]

    def step(window):
        length, x, y = walk_pair(base, window)
        assert x < width and y < width, (t, x, y)
        return length, x * width + y

    return step


out = ["//! GENERATED by tools/mp3tables/gen.py from minimp3 (CC0, see third_party/minimp3). Do not",
       "//! edit. Pair tables: entry x * width + y. Count1 tables: entry v * 8 + w * 4 + x * 2 + y.",
       'const Code = @import("../../huffman.zig").Code;', ""]


def emit(name, codes, size):
    assert sorted(codes) == list(range(size)), f"{name}: {len(codes)} of {size} symbols"
    out.append(f"pub const {name} = [{size}]Code{{")
    for s in range(size):
        c, length = codes[s]
        out.append(f"    .{{ .code = 0x{c:x}, .len = {length} }},")
    out.append("};")
    out.append("")


for t, width in WIDTH.items():
    emit(f"table{t}", enumerate_codes(pair_step(t)), width * width)
emit("count1_a", enumerate_codes(lambda w: walk_quad(tab32, w)), 16)
emit("count1_b", enumerate_codes(lambda w: walk_quad(tab33, w)), 16)

names = []
for t in range(32):
    src_t = t if t < 16 else (16 if t < 24 else 24)
    names.append("null" if src_t not in WIDTH else f"&table{src_t}")
out.append("/// Pair table per table_select (0..31): null for 0, 4 and 14; 16..23 share table 16's code and")
out.append("/// 24..31 table 24's, with different linbits.")
out.append("pub const pair = [32]?[]const Code{ " + ", ".join(names) + " };")
out.append("pub const width = [32]u8{ " + ", ".join(str(0 if t in (0, 4, 14) else WIDTH[t if t < 16 else (16 if t < 24 else 24)]) for t in range(32)) + " };")
out.append("pub const linbits = [32]u4{ " + ", ".join(map(str, linbits)) + " };")
open(f"{root}/ref/mp3/tables/huffman.zig", "w").write("\n".join(out) + "\n")

pd = open(f"{root}/third_party/pdmp3/pdmp3.c").read()
m = re.search(r"g_synth_dtbl\[512\]\s*=\s*\{(.*?)\}", pd, re.S)
d = [float(v) for v in re.findall(r"-?\d+\.\d+", m.group(1))]
assert len(d) == 512
# every coefficient is a whole multiple of 2^-16 (ISO prints 9 decimals of k / 65536)
ints = [round(v * 65536) for v in d]
assert all(abs(v * 65536 - k) < 0.01 for v, k in zip(d, ints)), "not multiples of 2^-16"
w = ["//! GENERATED by tools/mp3tables/gen.py from PDMP3 (public domain, see third_party/pdmp3). Do",
     "//! not edit. ISO/IEC 11172-3 synthesis window: D[i] = d[i] / 65536.",
     "pub const d = [512]i32{"]
for i in range(0, 512, 8):
    w.append("    " + ", ".join(str(k) for k in ints[i:i + 8]) + ",")
w.append("};")
open(f"{root}/ref/mp3/tables/synth_window.zig", "w").write("\n".join(w) + "\n")
print("ok", len(WIDTH), "pair tables")

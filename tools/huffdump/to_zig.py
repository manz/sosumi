"""Turns huffdump output (book index length codeword) into ref/aac/tables/huffman.zig."""
import sys
from collections import defaultdict

SIZES = {0: 121, 1: 81, 2: 81, 3: 81, 4: 81, 5: 81, 6: 81, 7: 64, 8: 64, 9: 169, 10: 169, 11: 289}

books = defaultdict(dict)
for line in open(sys.argv[1]):
    book, index, length, code = line.split()
    books[int(book)][int(index)] = (int(length), int(code, 16))

print("//! GENERATED by tools/huffdump/gen.sh from the OpenCORE AAC decoder (Apache 2.0, see")
print("//! third_party/opencore-aac). Do not edit. Entry i is the codeword of index i.")
print("pub const Code = struct { code: u32, len: u5 };\n")
for book, size in SIZES.items():
    entries = books[book]
    assert sorted(entries) == list(range(size)), f"book {book} incomplete"
    name = "scalefactor" if book == 0 else f"book{book}"
    print(f"pub const {name} = [{size}]Code{{")
    for i in range(size):
        length, code = entries[i]
        print(f"    .{{ .code = 0x{code:x}, .len = {length} }},")
    print("};\n")
print("/// Spectral codebooks 1..11; index 0 is book 1.")
print("pub const spectral = [11][]const Code{ " + ", ".join(f"&book{b}" for b in range(1, 12)) + " };")
